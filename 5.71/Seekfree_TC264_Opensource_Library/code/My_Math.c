/**
 * @brief 快速平方根函数（倒数平方根算法）
 * @param number 输入正数
 * @return float 平方根值
 *
 * 功能：快速计算平方根，使用著名的"快速倒数平方根"算法
 *
 * 算法原理（Quake III Arena中的著名算法）：
 * 1. 使用整数位操作进行初始估计
 * 2. 牛顿迭代法精化结果
 * 3. 原始算法计算1/sqrt(x)，这里乘以x得到sqrt(x)
 *
 * 魔法常数：0x5f3759df
 * 精度：1-2次牛顿迭代后，误差<0.175%
 * 速度：比标准sqrt快很多（避免浮点除法和平方根指令）
 *
 * 注意：需要确保输入为正数
 */
float my_sqrt(float number)
{
    long i;
    float x, y;
    const float f = 1.5F;  // 牛顿迭代公式中的常数

    x = number * 0.5F;     // x = number/2，用于牛顿迭代
    y = number;            // 保存原始值

    /* 1. 整数位操作：获得1/sqrt(number)的初始估计 */
    i = *(long*)&y;                       // 将浮点数按位解释为整数
    i = 0x5f3759df - (i >> 1);            // 魔法操作：初始估计
    y = *(float*)&i;                      // 将整数按位解释回浮点数

    /* 2. 牛顿迭代法精化：y = y*(1.5 - 0.5*number*y*y) */
    y = y * (f - (x * y * y));            // 第一次迭代
    y = y * (f - (x * y * y));            // 第二次迭代（可选，提高精度）

    /* 3. 返回平方根：sqrt(number) = number * (1/sqrt(number)) */
    return number * y;
}

