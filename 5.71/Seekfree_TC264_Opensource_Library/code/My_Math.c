/**********************************************************************************************************
*函 数 名: SafeArcsin
*功能说明: 带有安全区域的反正弦函数，防止输入超出[-1,1]范围导致NAN值
*形    参: v - 输入值
*返 回 值: 反正弦值(弧度)
**********************************************************************************************************/
float SafeArcsin(float v)
{
    // 检查输入是否为NAN(非数值)
    if (isnan(v)) {
        return 0.0;  // 如果是NAN，返回0避免后续计算错误
    }

    // 限制输入值在[-1, 1]范围内，避免asin函数域错误
    if (v >= 1.0f) {
        return M_PI_F/2;  // 输入≥1时，反正弦值为π/2(90度)
    }
    if (v <= -1.0f) {
        return -M_PI_F/2; // 输入≤-1时，反正弦值为-π/2(-90度)
    }

    // 输入在有效范围内，计算反正弦值
    return asinf(v);
}

/**********************************************************************************************************
*函 数 名: ConstrainFloat
*功能说明: 浮点型限幅函数，将数值限制在[low, high]范围内
*形    参: amt - 输入值, low - 下限, high - 上限
*返 回 值: 限幅后的值
**********************************************************************************************************/
float ConstrainFloat(float amt, float low, float high)
{
    // 检查输入是否为NAN
    if (isnan(amt))
    {
        // NAN值处理：返回范围中点
        return (low+high)*0.5f;
    }

    // 三重条件运算符实现限幅：
    // 1. 如果amt < low，返回low
    // 2. 如果amt > high，返回high
    // 3. 否则返回amt
    return ((amt)<(low)?(low):((amt)>(high)?(high):(amt)));
}

/**********************************************************************************************************
*函 数 名: ConstrainInt16
*功能说明: 16位有符号整型限幅函数
*形    参: amt - 输入值, low - 下限, high - 上限
*返 回 值: 限幅后的值
**********************************************************************************************************/
int16_t ConstrainInt16(int16_t amt, int16_t low, int16_t high)
{
    // 与浮点版本类似，但不检查NAN(整型不会有NAN)
    return ((amt)<(low)?(low):((amt)>(high)?(high):(amt)));
}
/**********************************************************************************************************
*函 数 名: ApplyDeadbandInt
*功能说明: 对整型数值应用死区，当值在死区内时置零
*形    参: value - 输入值, deadband - 死区大小
*返 回 值: 处理后的值
**********************************************************************************************************/
int32_t ApplyDeadbandInt(int32_t value, int32_t deadband)
{
    // 检查绝对值是否小于死区
    if (abs(value) < deadband)
    {
        value = 0;  // 在死区内，输出为零
    }
    else if (value > 0)  // 正数且超出死区
    {
        value -= deadband;  // 减去死区值
    }
    else if (value < 0)    // 负数且超出死区
    {
        value += deadband;  // 加上死区值(实际上是减去负的死区)
    }
    // 如果value == 0，保持0不变

    return value;
}


/**********************************************************************************************************
*函 数 名: ApplyDeadbandFloat
*功能说明: 对浮点型数值应用死区
*形    参: value - 输入值, deadband - 死区大小
*返 回 值: 处理后的值
**********************************************************************************************************/
float ApplyDeadbandFloat(float value, float deadband)
{
    // 浮点版本，逻辑与整型版本相同
    if (abs(value) < deadband)
    {
        value = 0;
    }
    else if (value > 0)
    {
        value -= deadband;
    }
    else if (value < 0)
    {
        value += deadband;
    }
    return value;
}

