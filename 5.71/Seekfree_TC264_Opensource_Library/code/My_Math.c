/**
 * @brief 快速atan2函数（四象限反正切）
 * @param y y坐标值
 * @param x x坐标值
 * @return REAL 角度（弧度），范围取决于编译选项
 *
 * 功能：快速计算atan2(y,x)，即点(x,y)与x轴正方向的夹角
 *
 * 算法原理：
 * 1. 将问题规约到第一象限（0-45度）
 * 2. 使用预计算的查找表进行插值
 * 3. 根据原始象限调整角度
 *
 * 精度：使用256个元素的查找表，线性插值
 * 速度：比标准atan2快很多，适合实时系统
 *
 * 角度范围：
 * - 默认：-π 到 π（-180° 到 180°）
 * - 启用ZERO_TO_TWOPI宏：0 到 2π（0° 到 360°）
 */
REAL fast_atan2(REAL y, REAL x)
{
    REAL x_abs, y_abs, z;          // 绝对值、比值
    REAL alpha, angle, base_angle; // 插值参数、角度
    int index;                     // 查找表索引

    /* 特殊处理：零值情况 */
    /* 注意：原注释有误，应该是(x==0 && y==0)才返回0 */
    if ((y == 0.0f) || (x == 0.0f)) // 原代码逻辑，可能有问题
    // if ((y == 0.0f) && (x == 0.0f)) // 应该是这样
        angle = 0.0f;
    else
    {
        /* 1. 计算绝对值，规约到第一象限 */
        y_abs = my_abs(y);
        x_abs = my_abs(x);

        /* 2. 计算比值z = min(|y|,|x|)/max(|y|,|x|)，将角度规约到0-45度 */
        // z = (y_abs < x_abs ? y_abs / x_abs : x_abs / y_abs); // 等价的三元表达式
        if (y_abs < x_abs)
            z = y_abs / x_abs;  // 角度小于45度
        else
            z = x_abs / y_abs;  // 角度大于45度，但通过取倒数仍在0-1范围

        /* 3. 当比值很小时，直接用比值近似角度（小角度近似：tanθ ≈ θ） */
        if (z < TAN_MAP_RES)  // TAN_MAP_RES = 0.003921569（约0.225°）
            base_angle = z;    // 直接使用比值作为角度（弧度）
        else
        {
            /* 4. 查找表插值计算基础角度（0-45度） */
            /* 计算插值位置：alpha = z * 256 - 0.5 */
            alpha = z * (REAL)TAN_MAP_SIZE - .5f;
            index = (int)alpha;           // 整数部分作为索引
            alpha -= (REAL)index;         // 小数部分作为插值系数

            /* 线性插值：base = table[index] + (table[index+1] - table[index]) * alpha */
            base_angle = fast_atan_table[index];
            base_angle += (fast_atan_table[index + 1] - fast_atan_table[index]) * alpha;
        }

        /* 5. 根据原始(x,y)的象限，将基础角度扩展到完整范围 */
        if (x_abs > y_abs)
        {
            /* 情况1：|x| > |y|，角度在-45°到45°或135°到225°（即靠近x轴） */
            if (x >= 0.0f)
            {
                /* 第一或第四象限（-45°到45°） */
                if (y >= 0.0f)
                    angle = base_angle;       // 第一象限（0°到45°）
                else
                    angle = -base_angle;      // 第四象限（-45°到0°）
            }
            else
            {
                /* 第二或第三象限（135°到180°或-180°到-135°） */
                angle = 3.14159265358979323846f;  // π
                if (y >= 0.0f)
                    angle -= base_angle;      // 第二象限（135°到180°）
                else
                    angle = base_angle - angle; // 第三象限（-180°到-135°）
            }
        }
        else
        {
            /* 情况2：|y| > |x|，角度在45°到135°或-135°到-45°（即靠近y轴） */
            if (y >= 0.0f)
            {
                /* 第一或第二象限（45°到135°） */
                angle = 1.57079632679489661923f;  // π/2
                if (x >= 0.0f)
                    angle -= base_angle;      // 第一象限（45°到90°）
                else
                    angle += base_angle;      // 第二象限（90°到135°）
            }
            else
            {
                /* 第三或第四象限（-135°到-45°） */
                angle = -1.57079632679489661923f; // -π/2
                if (x >= 0.0f)
                    angle += base_angle;      // 第四象限（-90°到-45°）
                else
                    angle -= base_angle;      // 第三象限（-135°到-90°）
            }
        }
    }

    /* 6. 可选：将角度范围从(-π,π)转换到(0,2π) */
#ifdef ZERO_TO_TWOPI
    if (angle < 0)
        return (angle + TWOPI);  // 负角度加上2π
    else
        return (angle);
#else
    return (angle);  // 默认返回(-π,π)范围
#endif
}

