/**********************************************************************************************************
*函 数 名: Pythagorous2
*功能说明: 计算2维向量长度(模)
*形    参: a - 第一维分量, b - 第二维分量
*返 回 值: 向量长度 sqrt(a² + b²)
**********************************************************************************************************/
float Pythagorous2(float a, float b)
{
    // 计算欧几里得距离: sqrt(a² + b²)
    return sqrtf(Sq(a)+Sq(b));
}

/**********************************************************************************************************
*函 数 名: Pythagorous3
*功能说明: 计算3维向量长度(模)
*形    参: a - x分量, b - y分量, c - z分量
*返 回 值: 向量长度 sqrt(a² + b² + c²)
**********************************************************************************************************/
float Pythagorous3(float a, float b, float c)
{
    // 3维欧几里得距离
    return sqrtf(Sq(a)+Sq(b)+Sq(c));
}

/**********************************************************************************************************
*函 数 名: WrapDegree360
*功能说明: 将角度限制在[0, 360)度范围内
*形    参: angle - 输入角度(度)
*返 回 值: 包装后的角度
**********************************************************************************************************/
float WrapDegree360(float angle)
{
    // 使用循环减法/加法实现包装
    if(angle >= 360)    // 角度≥360度
        angle -= 360;   // 减去360度
    if(angle < 0)       // 角度<0度
        angle += 360;   // 加上360度

    return angle;
}

/**********************************************************************************************************
*函 数 名: WrapRadiansPi
*功能说明: 将弧度限制在[-π, π)范围内
*形    参: radians - 输入弧度
*返 回 值: 包装后的弧度
**********************************************************************************************************/
float WrapRadiansPi(float radians)
{
    float radians_out;

    // 第一步：使用fmod将弧度限制在[0, 2π)或(-2π, 0]范围内
    // fmod返回x除以y的余数，符号与x相同
    radians = fmod(radians, 2*M_PI_F);

    // 第二步：调整到[-π, π)范围
    if(radians >= M_PI_F)  // 弧度在[π, 2π)范围内
    {
        radians_out = radians - 2*M_PI_F;  // 减去2π，得到[-π, 0)范围内的值
    }
    else if(radians < -M_PI_F)  // 弧度在(-2π, -π)范围内(理论上fmod不会产生，但保留)
    {
        radians_out = radians + 2*M_PI_F;  // 加上2π，得到[0, π)范围内的值
    }
    else  // 弧度已经在[-π, π)范围内
    {
        radians_out = radians;  // 直接返回
    }

    return radians_out;
}
