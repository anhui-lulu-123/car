/**
 * @brief 快速正弦函数核心（近似计算）
 * @param rad 输入弧度（假设在[-π,π]范围内）
 * @return double 正弦值
 *
 * 功能：快速近似计算sin(x)，使用多项式拟合
 *
 * 近似公式（经验公式）：
 * 对于|x|较小的情况：sin(x) ≈ x
 * 使用分段线性+二次修正
 *
 * 精度：中等，适合不需要高精度的实时应用
 * 范围：输入应在[-π,π]内，否则需要预处理
 */
double mx_sin(double rad)
{
    double sine;

    /* 1. 初步线性近似 */
    if (rad < 0)
        sine = rad * (1.27323954f + 0.405284735f * rad);  // 负角度
    else
        sine = rad * (1.27323954f - 0.405284735f * rad);  // 正角度

    /* 2. 二次修正（提高精度） */
    if (sine < 0)
        sine = sine * (-0.225f * (sine + 1) + 1);  // 负值修正
    else
        sine = sine * (0.225f * (sine - 1) + 1);   // 正值修正

    return sine;
}

/**
 * @brief 正弦函数（带范围处理）
 * @param rad 输入弧度（任意值）
 * @return double 正弦值
 *
 * 功能：计算任意弧度值的正弦
 * 通过取模将输入规约到[0,π]范围，并处理符号
 *
 * 处理步骤：
 * 1. 如果rad >= π，减去π并取反
 * 2. 调用mx_sin计算
 * 3. 根据象限调整符号
 */
double my_sin(double rad)
{
    int8 flag = 1;  // 符号标志：1=正，-1=负

    /* 1. 规约到[0,π]范围 */
    if (rad >= ONE_PI)      // 如果角度>=π
    {
        rad -= ONE_PI;      // 减去π
        flag = -1;          // 符号取反（sin(x+π) = -sin(x)）
    }

    /* 2. 计算正弦值并应用符号 */
    return mx_sin(rad) * flag;
}

/**
 * @brief 余弦函数
 * @param rad 输入弧度（任意值）
 * @return float 余弦值
 *
 * 功能：计算任意弧度值的余弦
 * 利用关系：cos(x) = sin(x + π/2)
 *
 * 处理步骤：
 * 1. 角度加π/2
 * 2. 规约到[0,π]范围
 * 3. 调用my_sin计算
 */
float my_cos(double rad)
{
    int8 flag = 1;  // 符号标志

    /* 1. 利用cos(x) = sin(x + π/2) */
    rad += ONE_PI / 2.0;  // 加π/2

    /* 2. 规约到[0,π]范围 */
    if (rad >= ONE_PI)
    {
        flag = -1;         // 符号取反
        rad -= ONE_PI;     // 减去π
    }

    /* 3. 计算正弦并应用符号 */
    return my_sin(rad) * flag;
}

/**
 * @brief 死区处理函数（类型1：带缩放的死区）
 * @param x 输入值
 * @param ref 参考值（死区中心）
 * @param zoom 死区半径
 * @return float 处理后的值
 *
 * 功能：对输入信号进行死区处理
 * 当输入在死区内时，输出被拉到参考值
 *
 * 处理逻辑：
 * 如果 x > ref：
 *   输出 = x - zoom，但如果结果<ref，则输出=ref
 * 如果 x < ref：
 *   输出 = x + zoom，但如果结果>ref，则输出=ref
 *
 * 效果：在ref附近创建死区，消除微小波动
 */
float my_deadzone(float x, float ref, float zoom)
{
    float t;  // 临时变量

    if (x > ref)
    {
        t = x - zoom;        // 向右移动zoom
        if (t < ref)         // 如果移动后仍小于ref
        {
            t = ref;         // 限制为ref
        }
    }
    else
    {
        t = x + zoom;        // 向左移动zoom
        if (t > ref)         // 如果移动后仍大于ref
        {
            t = ref;         // 限制为ref
        }
    }
    return (t);
}

/**
 * @brief 死区处理函数（类型2：硬死区）
 * @param x 输入值
 * @param ref 参考值（死区中心）
 * @param zoom 死区半径
 * @return float 处理后的值
 *
 * 功能：硬死区处理
 * 当输入在[ref-zoom, ref+zoom]范围内时，输出固定为ref
 * 否则输出原始值
 *
 * 效果：在ref附近创建完全平坦的区域
 */
float my_deadzone_2(float x, float ref, float zoom)
{
    float t;

    /* 检查是否在死区内 */
    if (x > (-zoom + ref) && x < (zoom + ref))
    {
        t = ref;  // 死区内：输出固定值
    }
    else
    {
        t = x;    // 死区外：输出原始值
    }

    return (t);
}

